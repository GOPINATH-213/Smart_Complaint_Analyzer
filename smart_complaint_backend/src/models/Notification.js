const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    firebaseUID: {
      type: String,
      required: true,
      index: true,
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    type: {
      type: String,
      required: true,
      enum: ['complaint_update', 'escalation_alert', 'assignment_alert', 'system'],
    },
    complaintId: {
      type: String,
      default: null,
    },
    isRead: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Notification', notificationSchema);
